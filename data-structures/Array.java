// Base class representing an Array data structure.
// In Java, arrays are homogeneous (all elements must be of the same data type).
// While we use int[] here, you can also create arrays of any other primitive
// (double[], char[], boolean[]) or any Object/data structure (String[], Tree[], List[]).
public class Array {
    // Contiguous memory container holding elements of the same type
    protected int[] data = {10, 20, 30, 40, 50};
}